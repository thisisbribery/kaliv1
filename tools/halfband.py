# Design the two halfband FIR stages for 4x oversampling (48k -> 96k -> 192k) and write dsp/halfband_coefs.h
import numpy as np, sys
def halfband(N, atten):
    assert (N - 3) % 4 == 0
    beta = 0.1102 * (atten - 8.7)
    n = np.arange(N) - (N - 1) / 2
    h = 0.5 * np.sinc(n / 2) * np.kaiser(N, beta)
    h[np.abs(n) % 2 == 0] = 0; h[(N - 1) // 2] = 0.5
    return h
def resp(h, f):  # f in units of the filter's sample rate
    n = np.arange(len(h)); return np.abs(np.exp(-2j * np.pi * np.outer(f, n)) @ h)
out = ["// Generated by tools/halfband.py. Kaiser-window halfband FIRs, centre tap 0.5.", "#pragma once", ""]
for name, N, fs, pass_hz, stop_hz in (("kHb1", 63, 96000, 20000, 28000), ("kHb2", 23, 192000, 20000, 72000)):
    h = halfband(N, 80)
    pb = resp(h, np.linspace(0, pass_hz / fs, 200)); sb = resp(h, np.linspace(stop_hz / fs, 0.5, 400))
    print(f"{name}: N={N} passband ripple {20*np.log10(pb.max()/pb.min()):.4f} dB, stopband {20*np.log10(sb.max()):.1f} dB", file=sys.stderr)
    ev = h[0::2]  # even-index taps (all nonzero for N=4k+3)
    out.append(f"// N = {N} at {fs} Hz; even-index taps, doubled for interpolation gain")
    out.append(f"static const float {name}[{len(ev)}] = {{" + ", ".join(f"{2*c:.9g}f" for c in ev) + "};")
    out.append(f"static constexpr int {name}Len = {N};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
